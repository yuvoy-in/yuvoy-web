/**
 * Derives the vector brand assets from the delivered master
 * `public/yuvoy-logo-vector.svg` (mark + YUVOY + tagline, traced outlines).
 * Never hand-edit the outputs; change this script and re-run it:
 *
 *   node scripts/generate-vector-brand.mjs
 *
 * Outputs:
 * - public/brand/yuvoy-mark-vector-{cream,forest}.svg   — the ensō alone
 * - public/brand/yuvoy-lockup-vector-{cream,forest}.svg — ensō + YUVOY
 * - src/components/brand/yuvoy-letter-paths.ts          — per-letter outline
 *   data for the intro veil, which animates the letters individually and
 *   colours them with brand tokens (no baked colour)
 *
 * The tagline ("Don't be a tourist", y ≥ 800 in the master, including its
 * small terracotta dot) is stripped from every output on owner direction.
 * Colours are re-expressed as brand tokens: the delivered green `#20372F`
 * becomes `forest` `#16362E`, the delivered terracotta `#BD6133` becomes
 * `terra` `#BE7149` (both within a hair of the source values), and the
 * on-dark strokes are `cream` `#F4EFE4`.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const master = readFileSync(join(root, "public/yuvoy-logo-vector.svg"), "utf8");

const CREAM = "#F4EFE4";
const FOREST = "#16362E";
const TERRA = "#BE7149";
const PAD = 16;

const pathMatches = [...master.matchAll(/<path d="([^"]+)" fill="([^"]+)"/g)];
if (pathMatches.length !== 2) {
  throw new Error(
    `expected 2 paths in the master, found ${pathMatches.length}`,
  );
}

/** Split a compound d-string into its subpaths, keeping each verbatim. */
function subpaths(d) {
  return d
    .split(/(?=M )/)
    .map((s) => s.trim())
    .filter(Boolean);
}

function bbox(d) {
  const pairs = [...d.matchAll(/(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)/g)];
  const xs = pairs.map((m) => Number(m[1]));
  const ys = pairs.map((m) => Number(m[2]));
  return {
    x0: Math.min(...xs),
    x1: Math.max(...xs),
    y0: Math.min(...ys),
    y1: Math.max(...ys),
  };
}

function union(boxes) {
  return {
    x0: Math.min(...boxes.map((b) => b.x0)),
    x1: Math.max(...boxes.map((b) => b.x1)),
    y0: Math.min(...boxes.map((b) => b.y0)),
    y1: Math.max(...boxes.map((b) => b.y1)),
  };
}

const [green, terra] = pathMatches.map(([, d]) =>
  subpaths(d).map((s) => ({ d: s, box: bbox(s) })),
);

// Classification by geometry (measured off the master): tagline glyphs and
// their dot sit at y ≥ 800, the YUVOY letterforms at 600 < y < 800, the
// brush ensō above 600. The terracotta path holds the ensō dot (~y 303) and
// the tagline dot (~y 820).
const tagline = (s) => s.box.y0 >= 800;
const isLetter = (s) => !tagline(s) && s.box.y0 > 600;
const markSubs = green.filter((s) => !tagline(s) && !isLetter(s));
const letterSubs = green.filter(isLetter);
const ensoDot = terra.find((s) => !tagline(s));
if (!ensoDot || markSubs.length === 0 || letterSubs.length === 0) {
  throw new Error("classification came up empty; master layout changed?");
}

// Merge letter subpaths whose x-ranges overlap (the O is outer + counter;
// they must stay in one path so the winding keeps the hole), then order
// left to right.
const letters = [];
for (const sub of [...letterSubs].sort((a, b) => a.box.x0 - b.box.x0)) {
  const prev = letters.at(-1);
  if (prev && sub.box.x0 <= prev.box.x1) {
    prev.d += " " + sub.d;
    prev.box = union([prev.box, sub.box]);
  } else {
    letters.push({ d: sub.d, box: { ...sub.box } });
  }
}
if (letters.length !== 5) {
  throw new Error(`expected 5 letterforms, found ${letters.length}`);
}

const markBox = union([...markSubs.map((s) => s.box), ensoDot.box]);
const lockupBox = union([markBox, ...letters.map((l) => l.box)]);

function viewBox(box) {
  const x = box.x0 - PAD;
  const y = box.y0 - PAD;
  return `${x} ${y} ${box.x1 - box.x0 + PAD * 2} ${box.y1 - box.y0 + PAD * 2}`;
}

function svg({ box, stroke, withLetters }) {
  const letterPaths = withLetters
    ? letters.map((l) => `  <path d="${l.d}" fill="${stroke}"/>`)
    : [];
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox(box)}" fill="none">`,
    `  <!-- Generated by scripts/generate-vector-brand.mjs; do not hand-edit. -->`,
    `  <path d="${markSubs.map((s) => s.d).join(" ")}" fill="${stroke}"/>`,
    `  <path d="${ensoDot.d}" fill="${TERRA}"/>`,
    ...letterPaths,
    `</svg>`,
    ``,
  ].join("\n");
}

const outputs = [
  [
    "public/brand/yuvoy-mark-vector-cream.svg",
    { box: markBox, stroke: CREAM, withLetters: false },
  ],
  [
    "public/brand/yuvoy-mark-vector-forest.svg",
    { box: markBox, stroke: FOREST, withLetters: false },
  ],
  [
    "public/brand/yuvoy-lockup-vector-cream.svg",
    { box: lockupBox, stroke: CREAM, withLetters: true },
  ],
  [
    "public/brand/yuvoy-lockup-vector-forest.svg",
    { box: lockupBox, stroke: FOREST, withLetters: true },
  ],
];
for (const [file, spec] of outputs) {
  writeFileSync(join(root, file), svg(spec));
  console.log(`wrote ${file}`);
}

// The intro's letter module: verbatim outline data plus the shared vertical
// window every letter renders in, so the five sit on one baseline.
const letterBand = union(letters.map((l) => l.box));
const ts = [
  "/**",
  " * Generated by scripts/generate-vector-brand.mjs from",
  " * public/yuvoy-logo-vector.svg; do not hand-edit — re-run the script.",
  " *",
  " * The five YUVOY letterforms as verbatim outline subpaths in the",
  " * master's coordinate space, ordered left to right. Every letter renders",
  " * in the same vertical window (LETTER_TOP/LETTER_HEIGHT) so the word",
  " * shares one baseline; widths differ per letterform.",
  " */",
  "",
  `export const LETTER_TOP = ${letterBand.y0 - 8};`,
  `export const LETTER_HEIGHT = ${letterBand.y1 - letterBand.y0 + 16};`,
  "",
  "export const YUVOY_LETTERS: ReadonlyArray<{",
  "  x: number;",
  "  width: number;",
  "  d: string;",
  "}> = [",
  ...letters.map(
    (l) =>
      `  { x: ${l.box.x0 - 2}, width: ${l.box.x1 - l.box.x0 + 4}, d: "${l.d}" },`,
  ),
  "];",
  "",
].join("\n");
writeFileSync(join(root, "src/components/brand/yuvoy-letter-paths.ts"), ts);
console.log("wrote src/components/brand/yuvoy-letter-paths.ts");
